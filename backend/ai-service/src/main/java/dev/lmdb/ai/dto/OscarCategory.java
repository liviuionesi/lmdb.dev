package dev.lmdb.ai.dto;

/** An Academy Award category a search can ask for the winning movies of. */
public enum OscarCategory {
  /** The film that won Best Picture. */
  BEST_PICTURE,
  /** Films in which an actor won Best Actor. */
  BEST_ACTOR,
  /** Films in which an actress won Best Actress. */
  BEST_ACTRESS,
  /** Films in which an actor won Best Supporting Actor. */
  BEST_SUPPORTING_ACTOR,
  /** Films in which an actress won Best Supporting Actress. */
  BEST_SUPPORTING_ACTRESS,
  /** Films for which a director won Best Director. */
  BEST_DIRECTOR
}
